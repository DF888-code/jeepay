-- 遷移 0002：管理者建立帳號或重設密碼時，要求本人第一次登入後變更密碼
--
-- 為什麼需要：臨時密碼由管理者產生並轉交，若不強制變更，管理者會一直知道員工的密碼。
-- 只新增欄位，不修改或刪除既有資料。
-- =====================================================================

ALTER TABLE users
    ADD COLUMN must_change_password TINYINT(1) NOT NULL DEFAULT 0
    COMMENT '1 = 登入後必須先變更密碼才能使用一般功能'
    AFTER must_enroll_2fa;
